#!/usr/bin/env python3

import argparse
import gzip
import subprocess
import sys
import re

def parse_args():
    p = argparse.ArgumentParser(
        description="fix reads in FASTQ reads in gzipped files generated by BGI"
    )
    p.add_argument("-i", "--input", required=True, help="Input FASTQ.GZ")
    p.add_argument("-o", "--output", required=True, help="Output FASTQ.GZ")
    p.add_argument("-t", "--threads", type=int, default=1, help="Threads for pigz (default: 1)")
    return p.parse_args()

def main():
    args = parse_args()

    # Start pigz for output compression
    pigz = subprocess.Popen(
        ["pigz", "-p", str(args.threads), "-c"],
        stdin=subprocess.PIPE,
        stdout=open(args.output, "wb")
    )
    suffix_re = re.compile(rb"^(@\S+?)(/[12])(\s.*)?$")

    kept = 0

    with gzip.open(args.input, "rb") as fin:
        while True:
            h = fin.readline()
            if not h:
                break

            s = fin.readline()
            p = fin.readline()
            q = fin.readline()

            if not q:
                break

            m = suffix_re.match(h.rstrip(b"\n"))
            if m:
                new_h = m.group(1)
                if m.group(3):
                    new_h += m.group(3)
                h = new_h + b"\n"

            pigz.stdin.write(h)
            pigz.stdin.write(s)
            pigz.stdin.write(p)
            pigz.stdin.write(q)

            kept += 1
            if kept % 1_000_000 == 0:
                print(f"processed {kept:,} reads", file=sys.stderr)

    pigz.stdin.close()
    pigz.wait()

    print(f"Done. Total reads processed: {kept:,}", file=sys.stderr)

if __name__ == "__main__":
    main()
